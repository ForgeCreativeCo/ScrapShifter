// Packs sounds as base64 so the game can decode them when index.html is opened from file://
// (browsers block fetch() of local files). Run after adding or replacing a sound: node tools/pack-sfx.js
//   sfx/*.mp3        -> js/sfxdata.js   (SFX_DATA, loaded with the page)
//   sfx/music/*.mp3  -> js/musicdata.js (MUSIC_DATA, music and ambience; loaded after start by maps that use it)
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
function pack(dir, out, name) {
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.mp3')).sort();
  const body = files.map(f => `'${f.slice(0, -4)}':'${fs.readFileSync(path.join(dir, f)).toString('base64')}'`).join(',\n');
  fs.writeFileSync(path.join(root, 'js', out), `// Generated by tools/pack-sfx.js. Do not edit by hand.\nconst ${name}={\n${body}};\n`);
  console.log(`packed ${files.length} sounds into js/${out}`);
}
pack(path.join(root, 'sfx'), 'sfxdata.js', 'SFX_DATA');
pack(path.join(root, 'sfx', 'music'), 'musicdata.js', 'MUSIC_DATA');
