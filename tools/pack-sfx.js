// Packs sfx/*.mp3 into js/sfxdata.js as base64 so the game can decode them when index.html is opened from file://
// (browsers block fetch() of local files). Run after adding or replacing a sound: node tools/pack-sfx.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'sfx');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.mp3')).sort();
const body = files.map(f => `'${f.slice(0, -4)}':'${fs.readFileSync(path.join(dir, f)).toString('base64')}'`).join(',\n');
fs.writeFileSync(path.join(root, 'js', 'sfxdata.js'),
  `// Generated by tools/pack-sfx.js from sfx/*.mp3. Do not edit by hand.\nconst SFX_DATA={\n${body}};\n`);
console.log(`packed ${files.length} sounds`);
